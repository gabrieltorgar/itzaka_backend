"""La configuración de folios de la organización (iteracion-25 #2 · US-142).

``GET /api/folio-settings/`` da un renglón por tipo de documento con su
modalidad, su clave y el siguiente folio; ``PUT /api/folio-settings/<tipo>/``
lo cambia (sólo el administrador, US-140) y ``GET …/<tipo>/preview/`` dice qué
folio saldría con una clave antes de guardarla.
"""

import pytest
from rest_framework import status
from rest_framework.test import APIClient

from apps.accounts.tests.factories import UserFactory
from apps.folios.codes import DocumentType, Mode
from apps.folios.services import assign_folio, configure_folios
from apps.team.tests.factories import MembershipFactory

URL = "/api/folio-settings/"
SOLO_ADMIN = "Sólo el administrador de la empresa puede hacer esto."


def como(user, empresa_id=None) -> APIClient:
    client = APIClient()
    client.force_authenticate(user=user)
    if empresa_id is not None:
        client.credentials(HTTP_X_EMPRESA=str(empresa_id))
    return client


@pytest.fixture
def admin(db):
    return UserFactory()


@pytest.mark.django_db
class TestLaConfiguracion:
    def test_every_document_type_starts_autogenerated(self, admin) -> None:
        """Flujo principal - Sin configurar, todo es «Autogenerado»."""
        response = como(admin).get(URL)

        assert response.status_code == status.HTTP_200_OK
        rows = response.data
        assert list(rows) == DocumentType.values
        assert rows["quote"]["label"] == "Cotizaciones"
        assert {row["mode"] for row in rows.values()} == {Mode.AUTO}
        assert rows["quote"]["next_folio"].startswith("COT-")

    def test_the_admin_sets_a_prefix_and_sees_the_next_folio(self, admin) -> None:
        """Flujo principal - Con clave: el siguiente folio se ve antes de crear nada."""
        response = como(admin).put(
            f"{URL}quote/", {"mode": "sequential", "prefix": "ven"}, format="json"
        )

        assert response.status_code == status.HTTP_200_OK
        assert response.data["mode"] == "sequential"
        assert response.data["prefix"] == "VEN"
        assert response.data["next_folio"] == "VEN-1"

    def test_an_invalid_prefix_says_why_under_its_field(self, admin) -> None:
        """Caso alternativo - VAL-08 · Una clave larga o con símbolos no se guarda."""
        response = como(admin).put(
            f"{URL}quote/", {"mode": "sequential", "prefix": "VENTAS"}, format="json"
        )

        assert response.status_code == status.HTTP_400_BAD_REQUEST
        assert response.data["prefix"] == [
            "La clave lleva de 1 a 5 letras o números, sin espacios ni símbolos."
        ]

    def test_an_unknown_mode_is_rejected(self, admin) -> None:
        response = como(admin).put(f"{URL}quote/", {"mode": "manual"}, format="json")

        assert response.status_code == status.HTTP_400_BAD_REQUEST
        assert "mode" in response.data

    def test_an_unknown_document_type_is_not_found(self, admin) -> None:
        response = como(admin).put(
            f"{URL}factura/", {"mode": "sequential", "prefix": "FAC"}, format="json"
        )

        assert response.status_code == status.HTTP_404_NOT_FOUND

    def test_preview_continues_the_prefix_counter(self, admin) -> None:
        """Caso de borde - VEN llegó a 100: la vista previa dice VEN-101."""
        configure_folios(
            owner=admin,
            document_type=DocumentType.QUOTE,
            mode=Mode.SEQUENTIAL,
            prefix="VEN",
        )
        for _ in range(100):
            assign_folio(owner=admin, document_type=DocumentType.QUOTE)
        configure_folios(
            owner=admin,
            document_type=DocumentType.QUOTE,
            mode=Mode.SEQUENTIAL,
            prefix="OBR",
        )

        response = como(admin).get(
            f"{URL}payment/preview/", {"mode": "sequential", "prefix": "ven"}
        )

        assert response.status_code == status.HTTP_200_OK
        assert response.data == {"next_folio": "VEN-101"}

    def test_preview_of_an_invalid_prefix_says_why(self, admin) -> None:
        response = como(admin).get(
            f"{URL}quote/preview/", {"mode": "sequential", "prefix": "V$"}
        )

        assert response.status_code == status.HTTP_400_BAD_REQUEST
        assert "prefix" in response.data


@pytest.mark.django_db
class TestSoloLaEmpresa:
    def test_a_collaborator_sees_it_but_cannot_change_it(self, admin) -> None:
        """Criterio - US-140 · Un colaborador ve los folios y no los cambia."""
        colaborador = MembershipFactory(account=admin).user

        seen = como(colaborador).get(URL)
        changed = como(colaborador).put(
            f"{URL}quote/", {"mode": "sequential", "prefix": "VEN"}, format="json"
        )

        assert seen.status_code == status.HTTP_200_OK
        assert changed.status_code == status.HTTP_403_FORBIDDEN
        assert changed.data["detail"] == SOLO_ADMIN

    def test_settings_belong_to_the_company(self, admin) -> None:
        """Criterio - SEC-01 · SEC-02 · La clave de una empresa no aparece en otra."""
        configure_folios(
            owner=admin,
            document_type=DocumentType.QUOTE,
            mode=Mode.SEQUENTIAL,
            prefix="VEN",
        )
        otra = UserFactory()

        rows = como(otra).get(URL).data

        assert rows["quote"]["mode"] == Mode.AUTO
        assert rows["quote"]["prefix"] == ""

    def test_a_company_where_one_does_not_work_is_forbidden(self, admin) -> None:
        """Criterio - SEC-02 · Pedir otra empresa por la cabecera no la abre."""
        ajena = UserFactory()

        response = como(admin, empresa_id=ajena.id).put(
            f"{URL}quote/", {"mode": "sequential", "prefix": "VEN"}, format="json"
        )

        assert response.status_code == status.HTTP_403_FORBIDDEN

    def test_anonymous_is_rejected(self, db) -> None:
        assert APIClient().get(URL).status_code in (401, 403)
